    public static function find($slug)
    {
        $cases = self::all();
        
        // Ищем не по ключу массива, а по полю 'slug'
        foreach ($cases as $case) {
            if (($case['slug'] ?? '') === $slug) {
                return $case;
            }
        }
        
        // Или ищем по URL
        foreach ($cases as $case) {
            if (str_contains($case['url'] ?? '', $slug)) {
                return $case;
            }
        }
        
        return null;
    }

    public static function getByIndex($index)
    {
        $cases = array_values(self::all());
        return $cases[$index - 1] ?? null;
    }
